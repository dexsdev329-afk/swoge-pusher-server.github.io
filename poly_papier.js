/* ---- les calculs purs ---- */
function phi(x) {   /* repartition normale, Abramowitz-Stegun 7.1.26 (erreur < 1,5e-7) */
  const s = x < 0 ? -1 : 1, z = Math.abs(x) / Math.SQRT2, t = 1 / (1 + 0.3275911 * z);
  const y = 1 - (((((1.061405429 * t - 1.453152027) * t) + 1.421413741) * t - 0.284496736) * t + 0.254829592) * t * Math.exp(-z * z);
  return 0.5 * (1 + s * y);
}
function varianceRestante(sigma1m, tauS, L) {
  const s2 = sigma1m * sigma1m / 60;               /* par seconde */
  if (!(L > 0)) return s2 * tauS;
  return tauS >= L ? s2 * (tauS - L + L / 3) : s2 * tauS * tauS * tauS / (3 * L * L);
}
function probaUp(S, S0, sigma1m, tauS, L) {
  if (!(S > 0 && S0 > 0 && sigma1m > 0 && tauS > 0)) return null;
  const p = phi(Math.log(S / S0) / Math.sqrt(varianceRestante(sigma1m, tauS, L || 0)));
  return Math.min(0.999, Math.max(0.001, p));
}
function sigma(bougies) {
  const c = (bougies || []).map((b) => Number(b.c)).filter((x) => x > 0);
  const r = []; for (let i = 1; i < c.length; i++) r.push(Math.log(c[i] / c[i - 1]));
  if (r.length < 20) return null;
  const m = r.reduce((a, b) => a + b, 0) / r.length;
  return Math.sqrt(r.reduce((a, b) => a + (b - m) * (b - m), 0) / (r.length - 1));
}
/* Acheter pour `usd` en remontant le carnet des vendeurs ; frais par niveau. */
function remplit(asks, usd, taux) {
  const l = (asks || []).map((a) => ({ p: Number(a.price), q: Number(a.size) })).filter((a) => a.p > 0 && a.p < 1 && a.q > 0).sort((a, b) => a.p - b.p);
  let reste = usd, parts = 0, frais = 0;
  for (const a of l) {
    if (reste <= 1e-9) break;
    const q = Math.min(a.q, reste / a.p);
    parts += q; reste -= q * a.p; frais += q * taux * a.p * (1 - a.p);
  }
  const depense = usd - reste;
  return parts > 0 ? { parts, depense, prix: depense / parts, frais, meilleur: l.length ? l[0].p : null } : null;
}
function wilson(k, n) {
  if (!n) return null;
  const z = 1.96, p = k / n, d = 1 + z * z / n, c = (p + z * z / (2 * n)) / d, m = z * Math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d;
  return { p, bas: Math.max(0, c - m), haut: Math.min(1, c + m) };
}
function verdictAgent(a) {
  if (a.resolus < RESOLUS_ASSEZ) return 'Too few resolved bets to judge (' + a.resolus + '/' + RESOLUS_ASSEZ + ').';
  const z = a.v > 0 ? (a.sy - a.sp) / Math.sqrt(a.v) : 0;
  if (z >= 3 && a.pnl > 0) return 'Evidence of an edge after fees in this sample (skill score ' + z.toFixed(1) + ').';
  if (z >= 2) return 'Some evidence, could still be luck (skill score ' + z.toFixed(1) + ').';
  if (a.pnl < 0) return 'No edge: loses after the spread and fees (skill score ' + z.toFixed(1) + ').';
  return 'No evidence of an edge (skill score ' + z.toFixed(1) + ').';
}

